export const PLAY_STRINGS: Record<PlayLocale, Record<Key, string>> = { en, hu, de };
export type PlayKey = Key;

export function pt(locale: PlayLocale, key: PlayKey, params?: Record<string, string | number>): string {
  const raw = (PLAY_STRINGS[locale] ?? en)[key] ?? en[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

/** A kliens-oldali szkripteknek átadható szótár (csak a kért előtagú kulcsok). */
export function clientStrings(locale: PlayLocale, prefixes: string[]): Record<string, string> {
  const dict = PLAY_STRINGS[locale] ?? en;
  const out: Record<string, string> = {};
  for (const k of Object.keys(dict) as Key[]) {
    if (prefixes.some((p) => k.startsWith(p))) out[k] = dict[k];
  }
  return out;
}
